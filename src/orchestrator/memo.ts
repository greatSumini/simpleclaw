/**
 * 기록 전용 마커 — "이건 지시가 아니라 그냥 메모" 를 사용자가 명시적으로 표시하는 수단.
 *
 * 배경: repo 바인딩 채널에 들어온 메시지는 라우터가 무조건 repo-work로 처리한다
 * (router.ts의 channel-locked 브랜치). 그래서 "오늘 해야할 일" 같은 단순 기록을 붙여넣으면
 * 그 목록 전체가 작업 지시로 해석되어 파일 생성·커밋·푸시까지 실행되는 사고가 났다.
 *
 * LLM 의도 추론에 맡기면 오탐이 남으므로, 판정은 전적으로 사용자가 붙인 마커로만 한다 —
 * 코드에서 결정론적으로 검사하고, 마커가 있으면 스레드 생성도 엔진 실행도 하지 않는다.
 */

/** 메시지 맨 앞에 오면 "기록일 뿐, 실행하지 말 것"으로 해석되는 마커들. */
export const MEMO_MARKERS = ['📝', '📌', '🗒', '✍', '#기록', '#메모'] as const;

/**
 * 메시지가 기록 전용 마커로 시작하는지 검사한다.
 *
 * 마커는 **맨 앞에만** 인정한다. 본문 어디에나 있는 이모지를 인정하면 평범한 요청 안의
 * 이모지 때문에 실제 지시가 조용히 무시될 수 있다 — 무시는 사용자가 알아채기 어려운
 * 실패라서, 오탐(무시) 쪽을 오히려 더 보수적으로 막는다.
 */
export function isMemoMessage(text: string): boolean {
  const trimmed = text.trim();
  if (!trimmed) return false;
  return MEMO_MARKERS.some((m) => trimmed.startsWith(m));
}
